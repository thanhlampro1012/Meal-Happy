import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const dir=await mkdtemp(join(tmpdir(),'hen-planning-'));
try{
  const bundled=await build({entryPoints:['app/lib/planning.ts'],bundle:true,format:'esm',platform:'node',write:false});
  const path=join(dir,'planning.mjs');await writeFile(path,bundled.outputFiles[0].contents);
  const {reorderPlanStops,nextStopTime,validPlanTimes,nextUpcomingPlan}=await import(path);
  const stops=[{placeId:'dinner',time:'18:30',note:'Món ăn'},{placeId:'coffee',time:'20:00',note:'Ít ngọt'},{placeId:'dessert',time:'21:15',note:'Chia đôi'}];
  const snapshot=JSON.stringify(stops);
  const reordered=reorderPlanStops(stops,2,0);
  assert.deepEqual(reordered.map(stop=>stop.placeId),['dessert','dinner','coffee']);
  assert.deepEqual(reordered.map(stop=>stop.time),['18:30','20:00','21:15']);
  assert.deepEqual(reordered.map(stop=>stop.note),['Chia đôi','Món ăn','Ít ngọt']);
  assert.equal(JSON.stringify(stops),snapshot);
  assert.equal(validPlanTimes('18:00',reordered),true);
  console.log('PASS reordering moves venues and notes while preserving chronological time slots');
  assert.equal(nextStopTime(stops),'22:45');
  assert.equal(nextStopTime([{...stops[0],time:'23:30'}]),'23:59');
  assert.equal(nextStopTime([{...stops[0],time:'23:59'}]),null);
  assert.equal(nextStopTime([{...stops[0],time:''}]),null);
  console.log('PASS adding stops handles late-night and temporarily blank time fields');
  assert.equal(validPlanTimes('18:30',stops),true);
  assert.equal(validPlanTimes('19:00',stops),false);
  assert.equal(validPlanTimes('18:30',[stops[0],{...stops[1],time:'18:30'}]),false);
  assert.equal(validPlanTimes('18:30',[{...stops[0],time:'24:00'}]),false);
  console.log('PASS plan times reject equal, reversed, invalid and pre-start slots');
  const make=(id,date,time,status='planned')=>({id,date,time,status,title:id,budget:0,notes:'',stops:[]});
  const plans=[make('tomorrow','2026-11-28','09:00'),make('morning','2026-11-27','08:00'),make('done','2026-11-27','20:30','done'),make('tonight','2026-11-27','21:00')];
  assert.equal(nextUpcomingPlan(plans,new Date('2026-11-27T13:00:00Z')).id,'tonight');
  assert.equal(plans[0].id,'tomorrow');
  assert.equal(nextUpcomingPlan([make('now','2026-11-27','20:00')],new Date('2026-11-27T13:00:00Z')).id,'now');
  console.log('PASS next appointment excludes earlier today and completed plans without reordering saved plans');
  assert.equal(nextUpcomingPlan([make('yesterday','2026-11-26','23:59'),make('past','2026-11-27','00:05'),make('next','2026-11-27','00:30')],new Date('2026-11-26T17:10:00Z')).id,'next');
  assert.equal(nextUpcomingPlan([make('past','2026-11-26','18:30')],new Date('2026-11-26T17:10:00Z')),undefined);
  console.log('PASS upcoming selection uses the Vietnam date across the UTC day boundary');
  console.log('5 planning checks passed.');
}finally{await rm(dir,{recursive:true,force:true});}
